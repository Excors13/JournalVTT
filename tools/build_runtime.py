#!/usr/bin/env python3
"""Bundle this repository's restricted named-import modules without runtime fetches.

Unsupported import/export forms and static cycles fail the build. Factories keep
private scopes; this codebase exports only constants, functions and classes.
"""
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
IMPORT=re.compile(r'^import\s*\{([^}]+)\}\s*from\s*["\'](\./[\w-]+\.js)["\'];\s*$',re.M)
EXPORT=re.compile(r'^export\s+(?:(?:async\s+)?function|class|const)\s+([A-Za-z_$][\w$]*)',re.M)
DYNAMIC=re.compile(r'\bimport\(["\'](\./[\w-]+\.js)["\']\)')

def build(root=None):
    root=Path(root or ROOT)
    sources={p.name:p.read_text(encoding="utf-8") for p in sorted((root/"scripts").glob("*.js")) if p.name not in {"bootstrap.js","runtime.js"}}
    compiled={};deps={}
    for name,source in sources.items():
        deps[name]=[]
        def imports(match):
            target=match[2][2:];deps[name].append(target)
            bindings=[]
            for item in match[1].split(","):
                parts=re.fullmatch(r'\s*([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?\s*',item)
                if not parts:raise ValueError(f"Unsupported named import in {name}: {item}")
                bindings.append(parts[1]+(":"+parts[2] if parts[2] else ""))
            return "const {"+",".join(bindings)+"}=__load("+json.dumps(target)+");"
        text=IMPORT.sub(imports,source)
        def dynamic(match):
            target=match[1][2:]
            if target not in sources:raise ValueError(f"Missing dynamic dependency {target}")
            return "Promise.resolve().then(()=>__load("+json.dumps(target)+"))"
        text=DYNAMIC.sub(dynamic,text)
        exports=EXPORT.findall(text)
        text=re.sub(r'^export\s+(?=(?:async\s+)?function\b|class\b|const\b)',"",text,flags=re.M)
        if re.search(r'^\s*(?:import|export)\b|\bimport\s*\(',text,re.M):raise ValueError(f"Unsupported module syntax in {name}")
        compiled[name]=text+"\nreturn {"+",".join(exports)+"};\n"
    visited=set();visiting=set()
    def visit(name):
        if name not in compiled:raise ValueError(f"Missing dependency {name}")
        if name in visiting:raise ValueError(f"Static import cycle at {name}")
        if name in visited:return
        visiting.add(name)
        for dep in deps[name]:visit(dep)
        visiting.remove(name);visited.add(name)
    for name in compiled:visit(name)
    result="// Generated by tools/build_runtime.py. Do not edit.\nconst __factories={\n"
    result+=",\n".join(json.dumps(name)+":()=>{\n"+code+"}" for name,code in compiled.items())
    result+="\n};\nconst __cache=new Map();\nfunction __load(name){if(!__cache.has(name))__cache.set(name,__factories[name]());return __cache.get(name);}\nexport function resumeCodex(){return __load(\"main.js\").resumeCodex();}\n"
    destination=root/"scripts/runtime.js";destination.write_text(result,encoding="utf-8")
    return destination

if __name__=="__main__":print(build())
